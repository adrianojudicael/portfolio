let currentLang = localStorage.getItem('portfolioLang') || 'fr';

function applyLanguage() {
    document.querySelectorAll('[data-key]').forEach(element => {
        const key = element.getAttribute('data-key');
        if (translations[currentLang][key]) {
            element.textContent = translations[currentLang][key];
        }
    });
    const langSwitch = document.getElementById('langSwitch');
    if (langSwitch) {
        langSwitch.textContent = currentLang === 'fr' ? 'EN' : 'FR';
    }
}

// Language switcher (persists across pages via localStorage)
const langSwitchBtn = document.getElementById('langSwitch');
if (langSwitchBtn) {
    langSwitchBtn.addEventListener('click', function() {
        currentLang = currentLang === 'fr' ? 'en' : 'fr';
        localStorage.setItem('portfolioLang', currentLang);
        applyLanguage();
    });
}

applyLanguage();

// Mobile menu
const hamburger = document.getElementById('hamburger');
const navMenu = document.querySelector('.nav-menu');
if (hamburger && navMenu) {
    hamburger.addEventListener('click', function() {
        navMenu.classList.toggle('active');
    });
}

// Close menu when clicking a link
document.querySelectorAll('.nav-menu a').forEach(link => {
    link.addEventListener('click', () => {
        if (navMenu) navMenu.classList.remove('active');
    });
});

// Post demo like button (only present on portfolio.html)
const likeBtn = document.getElementById('likeBtn');
if (likeBtn) {
    likeBtn.addEventListener('click', function() {
        this.classList.toggle('liked');
        const likeText = this.querySelector('span');
        if (this.classList.contains('liked')) {
            likeText.textContent = currentLang === 'fr' ? 'J\'aime' : 'Liked';
        } else {
            likeText.textContent = translations[currentLang].post_like;
        }
    });
}

// Contact form validation (only present on contact.html)
const contactForm = document.getElementById('contactForm');
if (contactForm) {
    contactForm.addEventListener('submit', function(e) {
        e.preventDefault();

        const name = document.getElementById('name').value.trim();
        const email = document.getElementById('email').value.trim();
        const message = document.getElementById('message').value.trim();

        if (!name || !email || !message) {
            alert(currentLang === 'fr' ? 'Veuillez remplir tous les champs.' : 'Please fill in all fields.');
            return;
        }

        if (!isValidEmail(email)) {
            alert(currentLang === 'fr' ? 'Veuillez entrer une adresse email valide.' : 'Please enter a valid email address.');
            return;
        }

        alert(currentLang === 'fr' ? 'Message envoyé avec succès!' : 'Message sent successfully!');
        this.reset();
    });
}

function isValidEmail(email) {
    const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    return emailRegex.test(email);
}
